// Captures d'écran des 20 scénarios officiels (docs/04) joués dans le fichier de démo, sans IA :
// on voit la phrase, le chemin suivi dans l'arbre et la réponse d'OKA. Résultat : docs/captures-scenarios/
//   npm run build:single && npm run captures
// Chromium de Playwright requis (npx playwright-core install chromium-headless-shell si absent).
import { chromium } from "playwright-core";
import fs from "fs";
import os from "os";

const racine = new URL("../", import.meta.url);
const demo = new URL("dist/OKA-avatar-parlant.html", racine).href;
const sortie = new URL("docs/captures-scenarios/", racine);
fs.mkdirSync(sortie, { recursive: true });
const { scenarios } = JSON.parse(fs.readFileSync(new URL("arbre/scenarios.json", racine), "utf8"));
const officiels = scenarios.filter(s => s.groupe !== "complement");
const shell = os.homedir() + "/.cache/ms-playwright/chromium_headless_shell-1148/chrome-linux/headless_shell";
const navigateur = await chromium.launch(fs.existsSync(shell) ? { executablePath: shell } : {});
const lignes = [];
for (const s of officiels) {
  const ctx = await navigateur.newContext({ viewport: { width: 1280, height: 800 } });
  const p = await ctx.newPage();
  await p.goto(demo); await p.waitForTimeout(600);
  // voix instantanée (pas de son en capture), parcours de l'arbre affiché
  await p.evaluate(() => { speechSynthesis.cancel(); speechSynthesis.speak = u => setTimeout(() => { u.onstart && u.onstart(); u.onend && u.onend(); }, 20);
    settings.trace = "1"; store.set("settings", settings); });
  if (await p.isVisible("#pf_demo")) { await p.click("#pf_demo"); await p.click("#pf_save"); }
  // l'accueil d'OKA arrive juste après le profil : on attend qu'il soit dit avant de jouer le scénario
  await p.waitForFunction(() => log.some(m => m.who === "oka" && /Comment allez-vous/.test(m.text)), null, { timeout: 20000 });
  await p.waitForFunction(() => !av.speaking && !sayQueue.length, null, { timeout: 20000 }); await p.waitForTimeout(500);
  await p.evaluate(() => { log.length = 0; renderLog(); pending = null; });
  await p.fill("#typeIn", s.phrase); await p.press("#typeIn", "Enter");
  await p.waitForFunction(() => !av.speaking && !sayQueue.length, null, { timeout: 20000 }); await p.waitForTimeout(400);
  const alerte = await p.isVisible("#alertBox");
  if (!alerte) { await p.click("#btnMenu"); await p.waitForTimeout(700); await p.click("#btnHist"); await p.waitForTimeout(400); }
  await p.screenshot({ path: new URL(s.id + ".png", sortie).pathname });
  const r = await p.evaluate(() => { const v = log.filter(m => m.who === "you").slice(-1)[0], o = log.filter(m => m.who === "oka").slice(-1)[0];
    return { chemin: (v && v.chemin || []).join(" › "), reponse: o ? o.text : "" }; });
  lignes.push({ s, ...r, alerte });
  console.log(s.id.padEnd(4), r.chemin, "→", (alerte ? "[alerte] " : "") + r.reponse.slice(0, 70));
  await ctx.close();
}
await navigateur.close();
const cell = t => String(t).replace(/\|/g, "\\|");
const GROUPES = { normal: "Normal", limite: "Limit", piege: "Trap" };
let md = "# The 20 official scenarios, played in the demo file\n\nGenerated by `npm run captures` on " + new Date().toISOString().slice(0, 10) +
  " (demo file, **no AI**: no key, no station). The four requests that normally go to the AI (N9, N10, L1, L5) show the local fallback here; " +
  "with Claude or the local model they go through the classifier, the answer and the output check (results in docs/07 §8).\n\n" +
  "| # | Group | Giselle says | Path in the tree | OKA answers | Screenshot |\n|---|---|---|---|---|---|\n";
for (const l of lignes) md += `| ${l.s.id} | ${GROUPES[l.s.groupe]} | « ${cell(l.s.phrase)} » | ${cell(l.chemin)} | ${l.alerte ? "**Alert started** · " : ""}${cell(l.reponse)} | [${l.s.id}](${l.s.id}.png) |\n`;
fs.writeFileSync(new URL("README.md", sortie), md);
console.log("→ docs/captures-scenarios/ (" + lignes.length + " captures + README.md)");
